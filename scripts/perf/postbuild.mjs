// Runs after the site and docs builds (see package.json "build"). Three jobs, all for speed:
//  1. Writes dist/sw.js, the docs offline cache: a service worker with the exact list of docs
//     pages, scripts, the stylesheet and the Latin fonts of this build, so that after a first visit
//     to any page of the site, opening the docs never waits on the network (~10-30 ms in Safari and
//     Firefox, which can't prerender). Big images are left out and cached when first viewed.
//  0. Inlines into every docs page the CSS that page actually uses (beasties) and moves the full
//     stylesheet to the end of the page, so the first paint no longer waits for 116 KB of CSS.
//     No inline script is involved, so the CSP's script-src 'self' still holds.
//  2. Adds <link rel="preload"> for the docs' first fonts to every docs page, so a first visit
//     straight to the docs fetches them alongside the stylesheet (Cloudflare also sends these as
//     103 Early Hints) instead of after it.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import Beasties from 'beasties'

const dist = fileURLToPath(new URL('../../dist/', import.meta.url))
const docs = join(dist, 'docs')
const clean = process.env.DOCS_CLEAN_URLS !== '0'

const walk = (dir) => readdirSync(dir).flatMap((n) => {
  const p = join(dir, n)
  return statSync(p).isDirectory() ? walk(p) : [p]
})
const url = (file) => '/' + relative(dist, file).split(sep).join('/')

// 0. Critical CSS per docs page (before the cache list, which hashes the pages).
// The pages are built without the dark class (docs/public/vp-theme.js adds it before the first paint), so
// the dark theme's rules are kept by name: otherwise a dark page would first paint light.
const beasties = new Beasties({ path: dist, publicPath: '/', preload: 'body', allowRules: [/\.dark\b/], pruneSource: false, inlineFonts: false, preloadFonts: false, compress: true, logLevel: 'warn' })
let inlined = 0
for (const f of walk(docs).filter((f) => f.endsWith('.html'))) {
  const html = readFileSync(f, 'utf8')
  if (html.includes('data-critical')) continue
  // VitePress writes its stylesheets as rel="preload stylesheet", which beasties doesn't treat as CSS.
  const plain = html.replace(/<link rel="preload stylesheet" href="([^"]+)" as="style">/g, '<link rel="stylesheet" href="$1">')
  const out = (await beasties.process(plain)).replace('<style>', '<style data-critical>')
  inlined += out.length - html.length
  writeFileSync(f, out)
}

const files = walk(docs)
const FIRST_FONTS = /overpass-(?:mono-)?latin-(?:400|600|800)-normal\.[\w-]+\.woff2$/
const isFirstFont = (f) => FIRST_FONTS.test(f) && !/mono-latin-(?:600|800)/.test(f)

// Pages: the URL people navigate to (clean: /docs/faq, /docs/ for an index).
const pages = files.filter((f) => f.endsWith('.html') && !f.endsWith(`${sep}404.html`)).map((f) => {
  const u = url(f)
  if (!clean) return u
  return u.endsWith('/index.html') ? u.slice(0, -'index.html'.length) : u.slice(0, -'.html'.length)
})
const assets = files.filter((f) => /\.(js|css)$/.test(f) || isFirstFont(f)).map(url)
const precache = [...pages, ...assets].sort()

const version = createHash('sha256').update(precache.join('\n')).update(files.filter((f) => f.endsWith('.html')).map((f) => readFileSync(f)).join('')).digest('hex').slice(0, 12)
const bytes = [...files.filter((f) => f.endsWith('.html') && !f.endsWith('404.html')), ...files.filter((f) => /\.(js|css)$/.test(f) || isFirstFont(f))]
  .reduce((n, f) => n + statSync(f).size, 0)

writeFileSync(join(dist, 'sw.js'), `// Generated by scripts/perf/postbuild.mjs. Do not edit.
// The docs offline cache: docs pages open from this cache, then refresh in the background.
// A content hash: a rebuild with nothing changed keeps the same worker and cache.
const VERSION = ${JSON.stringify(version)}
const CACHE = 'fcr-docs-' + VERSION
const PRECACHE = ${JSON.stringify(precache)}
const CLEAN = ${clean}

self.addEventListener('install', (event) => {
  // Chrome and Edge (static routing): docs pages and hashed files come straight from the cache without
  // starting this worker at all, which saves its start-up time on every click. Misses go to the network.
  // The first matching route wins. Hashed files never change, so any version's cache will do (an old
  // tab can still load its chunks). Pages must come from this version's cache only: a bare 'cache'
  // source searches every cache, oldest first, and would serve the previous deploy's pages.
  try {
    event.addRoutes?.([
      { condition: { urlPattern: '/docs/assets/*' }, source: 'cache' },
      { condition: { urlPattern: '/assets/*' }, source: 'cache' },
      { condition: { urlPattern: '/docs/*' }, source: { cacheName: CACHE } },
    ])?.catch(() => {})
  } catch {}
  // One failed file must not stop the rest; the docs still load from the network.
  event.waitUntil(caches.open(CACHE).then((c) => Promise.allSettled(PRECACHE.map((u) => c.add(u)))).then(() => self.skipWaiting()))
})

// Pages send 'warm' when a docs link is hovered or touched: receiving it starts this worker, so the
// click that follows doesn't wait for it to boot (Safari and Firefox, which have no static routing).
self.addEventListener('message', () => {})

self.addEventListener('activate', (event) => {
  // Keep this version and the one before it: a docs tab opened on the old version can still load its files.
  // caches.keys() lists caches in the order they were created, so the last other one is the previous version.
  event.waitUntil(caches.keys().then((keys) => {
    const others = keys.filter((k) => k.startsWith('fcr-docs-') && k !== CACHE)
    return Promise.all(others.slice(0, -1).map((k) => caches.delete(k)))
  }).then(() => self.clients.claim()))
})

// /docs/faq.html and /docs/faq are the same page; /docs/index.html is /docs/.
const pageKey = (u) => {
  let p = u.pathname
  if (CLEAN) p = p.replace(/index\\.html$/, '').replace(/\\.html$/, '')
  return u.origin + p
}

// Hashed files and images: any version's copy is right, so search every cache.
async function fromCacheFirst(req) {
  const hit = await caches.match(req)
  if (hit) return hit
  const res = await fetch(req)
  if (res.ok) (await caches.open(CACHE)).put(req, res.clone())
  return res
}

async function staleWhileRevalidate(event, key) {
  // Pages and unhashed files change between deploys: only this version's cache is right.
  const cache = await caches.open(CACHE)
  const hit = await cache.match(key)
  const fresh = fetch(event.request).then((res) => {
    if (res.ok && !res.redirected) cache.put(key, res.clone())
    return res
  })
  if (hit) {
    event.waitUntil(fresh.catch(() => {}))
    return hit
  }
  return fresh
}

self.addEventListener('fetch', (event) => {
  const req = event.request
  if (req.method !== 'GET') return
  const u = new URL(req.url)
  if (u.origin !== location.origin) return
  // Hashed files never change: the cache is always right.
  if (u.pathname.startsWith('/docs/assets/') || u.pathname.startsWith('/assets/')) return event.respondWith(fromCacheFirst(req))
  if (!u.pathname.startsWith('/docs')) return
  // Docs pages and their small unhashed files: answer from the cache, refresh it in the background.
  if (req.mode === 'navigate' || /\\.(js|css|json)$/.test(u.pathname)) return event.respondWith(staleWhileRevalidate(event, req.mode === 'navigate' ? pageKey(u) : req))
  // Anything else under /docs (images): cache after the first view.
  event.respondWith(fromCacheFirst(req))
})
`)

// Font preloads on every docs page, right after the charset.
const fonts = files.filter(isFirstFont).filter((f) => !/mono/.test(f)).map(url)
for (const f of files.filter((f) => f.endsWith('.html'))) {
  const html = readFileSync(f, 'utf8')
  if (html.includes('data-font-preload')) continue
  const tags = fonts.map((u) => `<link rel="preload" href="${u}" as="font" type="font/woff2" crossorigin data-font-preload>`).join('')
  writeFileSync(f, html.replace(/(<meta charset="[^"]*">)/i, `$1${tags}`))
}

console.log(`Docs critical CSS: ~${Math.round(inlined / 1024 / 24)} KB inlined per page.`)
console.log(`Docs offline cache: ${precache.length} files (${pages.length} pages), ${Math.round(bytes / 1024)} KB before compression; ${fonts.length} font preloads per docs page.`)
