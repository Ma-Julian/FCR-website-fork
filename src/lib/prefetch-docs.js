// Makes the jump from a page to the docs fast (goal: docs on screen within 100 ms of the click).
// The docs are a separate build (VitePress), so without help their stylesheet, scripts and fonts only
// start downloading after the click. Three layers, each skipped on Save-Data or 2G connections:
//  1. Chrome and Edge (speculation rules): the docs home page is prerendered as soon as this page has
//     loaded, and any other docs link prerenders after a short hover or on touch. The click then just
//     swaps in a page that is already drawn.
//  2. Every browser with service workers (Safari and Firefox included): the docs offline cache
//     (dist/sw.js, generated by scripts/perf/postbuild.mjs) is installed once this page is idle, so a
//     docs page opens from the device instead of the network.
//  3. Browsers without service workers: the docs home page and its first files are prefetched.
// None of this is needed for the links to work; if a step fails the page behaves as before.

const isDocs = (a) => {
  try { return /\/docs\//.test(new URL(a.href, location.href).pathname) } catch { return false }
}

const hinted = new Set()
function hint(url, as) {
  if (hinted.has(url)) return
  hinted.add(url)
  const l = document.createElement('link')
  l.rel = 'prefetch'
  l.href = url
  if (as) l.as = as
  document.head.appendChild(l)
}

let warmed = false
async function warm(entry) {
  if (warmed) return
  warmed = true
  try {
    const res = await fetch(entry, { priority: 'low', credentials: 'same-origin' })
    if (!res.ok) return
    const doc = new DOMParser().parseFromString(await res.text(), 'text/html')
    const abs = (u) => new URL(u, entry).href
    doc.querySelectorAll('link[rel~="stylesheet"][href], link[rel~="preload"][href]').forEach((l) => hint(abs(l.getAttribute('href')), l.getAttribute('as') || 'style'))
    doc.querySelectorAll('link[rel~="modulepreload"][href], script[src]').forEach((el) => hint(abs(el.getAttribute('href') || el.getAttribute('src')), 'script'))
  } catch { /* offline or blocked: the click still works */ }
}

function speculate(entry) {
  if (!HTMLScriptElement.supports?.('speculationrules')) return
  const s = document.createElement('script')
  s.type = 'speculationrules'
  s.textContent = JSON.stringify({
    prerender: [
      { source: 'list', urls: [entry], eagerness: 'immediate' },
      { source: 'document', where: { and: [{ href_matches: '/docs/*' }, { not: { href_matches: entry } }] }, eagerness: 'moderate' },
    ],
  })
  document.head.appendChild(s)
}

function offlineCache() {
  if (!('serviceWorker' in navigator)) return false
  const go = () => navigator.serviceWorker.register('/sw.js').catch(() => {})
  if (window.requestIdleCallback) requestIdleCallback(go, { timeout: 4000 })
  else setTimeout(go, 1500)
  return true
}

// Wakes the docs offline cache's worker when a docs link is hovered, focused or touched, so it is
// running by the time of the click (browsers stop idle workers after about 30 seconds).
let lastWake = 0
function wakeOnIntent() {
  const wake = (ev) => {
    const a = ev.target.closest?.('a[href]')
    if (!a || !isDocs(a) || !navigator.serviceWorker?.controller) return
    const now = Date.now()
    if (now - lastWake < 10000) return
    lastWake = now
    navigator.serviceWorker.controller.postMessage('warm')
  }
  document.addEventListener('pointerover', wake, { passive: true })
  document.addEventListener('touchstart', wake, { passive: true })
  document.addEventListener('focusin', wake)
}

export function mountDocsPrefetch() {
  const first = [...document.querySelectorAll('a[href]')].find(isDocs)
  if (!first) return
  const c = navigator.connection
  if (c && (c.saveData || /2g/.test(c.effectiveType || ''))) return
  // The docs home page, as a same-origin path ("/docs/").
  const entry = new URL(first.href, location.href).pathname
  const run = () => {
    speculate(entry)
    if (offlineCache()) wakeOnIntent()
    else warm(first.href)
  }
  if (document.readyState === 'complete') run()
  else window.addEventListener('load', run, { once: true })
}
